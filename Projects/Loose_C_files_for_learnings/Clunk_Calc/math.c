#include "math.h"

int adder(int a, int b)
{
    int result = a + b;

    return result;
}


int subber(int a, int b)
{
    int result = a - b;

    return result;
}


long long multer(int a, int b)
{
    long long result = (long long)a * b; //Casting to a long long

    return result;
}



float diver(int a, int b)
{
    float result = (float)a / b; // Casting one int to float

    return result;
}
